"""Generate firmware sources from the trained artifacts -> sims/bearing_ai/gen/.

  model_data.cc/.h   the int8 .tflite as a C array (+ quantisation constants)
  window_bank.h      a few *raw* vibration windows per class from the held-out
                     3 hp load (int16, 1/2048 g per LSB), replayed by the sim.
Usage: python gen_firmware.py
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np

from bearing import data

ROOT = Path(__file__).resolve().parents[1]
GEN = ROOT / "sims" / "bearing_ai" / "gen"
ART = Path(__file__).parent / "artifacts"
PER_CLASS = 8
LSB_PER_G = 2048


def carray(b: bytes | np.ndarray, per_line=16, fmt="0x{:02x}") -> str:
    vals = list(b)
    return ",\n".join("\t" + ", ".join(fmt.format(v) for v in vals[i:i + per_line])
                      for i in range(0, len(vals), per_line))


def main():
    GEN.mkdir(parents=True, exist_ok=True)
    meta = json.loads((ART / "model_meta.json").read_text())
    blob = (ART / "bearing_cnn_int8.tflite").read_bytes()

    (GEN / "model_data.h").write_text(f"""// GENERATED by python/gen_firmware.py -- do not edit.
#pragma once
#include <cstddef>
#include <cstdint>

namespace bearing_model {{
extern const unsigned char kModel[];
constexpr size_t kModelLen = {len(blob)};
constexpr int kWindow = {meta['window']};
constexpr int kClasses = {len(meta['classes'])};
constexpr float kInputScale = {meta['input_scale']!r}f;
constexpr int kInputZeroPoint = {meta['input_zero_point']};
constexpr float kLogitScale = {meta['logit_scale']!r}f;
constexpr int kLogitZeroPoint = {meta['logit_zero_point']};
constexpr int kSampleRateHz = {meta['fs_hz']};
constexpr const char *kClassNames[kClasses] = {{{", ".join(f'"{c}"' for c in meta['classes'])}}};
}} // namespace bearing_model
""")
    (GEN / "model_data.cc").write_text(f"""// GENERATED by python/gen_firmware.py -- do not edit.
#include "model_data.h"

namespace bearing_model {{
alignas(16) const unsigned char kModel[] = {{
{carray(blob)}
}};
}} // namespace bearing_model
""")

    xr, y, _ = data.test_set()
    rng = np.random.default_rng(1)
    banks, labels = [], []
    for c in range(len(data.CLASSES)):
        idx = rng.choice(np.where(y == c)[0], PER_CLASS, replace=False)
        for i in idx:
            banks.append(np.clip(np.round(xr[i] * LSB_PER_G), -32768, 32767).astype(np.int16))
            labels.append(c)
    banks = np.array(banks)
    (GEN / "window_bank.h").write_text(f"""// GENERATED by python/gen_firmware.py -- do not edit.
// {len(banks)} raw windows from the held-out 3 hp load, never seen in training.
#pragma once
#include <cstdint>

namespace bearing_model {{
constexpr int kBankWindows = {len(banks)};
constexpr int kBankPerClass = {PER_CLASS};
constexpr float kLsbPerG = {LSB_PER_G}.0f;
// label of window i = i / kBankPerClass (classes in kClassNames order)
static const int16_t kBank[kBankWindows][{meta['window']}] = {{
{",\n".join("{" + ", ".join(str(int(v)) for v in w) + "}" for w in banks)}
}};
}} // namespace bearing_model
""")
    print(f"wrote {GEN}: model {len(blob)} B, bank {banks.nbytes} B")


if __name__ == "__main__":
    main()
